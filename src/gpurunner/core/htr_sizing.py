@dataclass(frozen=True)
class Sizing:
    """Розкладка прогону на конкретному залізі."""

    shards: int
    threads_per_shard: int
    cores_used: float
    wasted_cores: float
    limited_by: str  # "vram" | "cpu" | "cap" — що обрізало ЧИСЛО шардів
    pages_per_hour: float
    #: Темп уперся в стелю карти (`CARD_MAX_LINES_PER_HOUR`), а не в суму
    #: шардів: додаткові шарди тут нічого не куплять.
    card_capped: bool = False
    #: Темп уперся в ЯДРА (`CORE_LINES_PER_HOUR`): шардів підняли більше, ніж
    #: є кому годувати. Окремим прапорцем, а не через `limited_by`: те поле
    #: каже, що обрізало ЧИСЛО шардів, і флот тут може бути цілком законним —
    #: просто працює він не на повний темп.
    cpu_capped: bool = False

    @property
    def usable(self) -> bool:
        return self.shards >= 1 and self.pages_per_hour > 0


def plan_sizing(
    *,
    cores: float,
    vram_gb: float,
    gb_per_shard: float = GB_PER_SHARD,
    max_shards: int = MAX_SHARDS,
    headroom: float = VRAM_HEADROOM,
    num_gpus: int = 1,
    shards_distributed: bool = True,
    lines_per_page: float = 0.0,
    cores_per_shard: float = MIN_CORES_PER_SHARD,
    frame_mpx: float = 0.0,
) -> Sizing:
    """Скільки шардів і потоків на цій машині.

    `cores` — **ефективні** ядра, тобто НАША ЧАСТКА машини, а не `cpu_count()`
    хоста: шрі-ланкійські бокси рапортували 96 і видавали менше за 64-ядерний
    V100. 🔴 `nproc` для цього НЕ годиться — він теж показує хост: 2026-08-19
    контейнер машини 39565 назвав 192 ядра при 48 проданих, і план поїхав на
    16 шардів × 8 потоків, тобто 128 потоків на 48 куплених ядер. Число дає
    `gate._measured`: `min(nproc, квота cgroup, `cpu_cores_effective` оффера)`.

    `vram_gb` — краще **вільна** VRAM, а не загальна: сусід на тій самій карті
    робить «16 ГБ» ще меншими.

    Непридатне залізо повертається як `shards=0` (а не винятком), щоб
    ранжування офферів могло просто його відкинути.
    """
    cores = max(0.0, float(cores))
    vram_gb = max(0.0, float(vram_gb))
    gb_per_shard = max(0.1, float(gb_per_shard))

    # 🔴🔴 Сумарна VRAM кількох карт чесна РІВНО ТОДІ, коли шарди по цих картах
    # розкладаються. Це не теорія, це два виміри одного дня:
    #
    #   · РОЗКЛАДКИ НЕМАЄ (стан коду до 2026-08-11): Царевка на RTX 3090×2 —
    #     «47.2 ГБ вільно» → 21 шард → усі 21 сіли на `cuda:0` з 24 ГБ
    #     (потрібно 54.6) → 1478 записів «out of memory» і 740 сторінок із
    #     1488 у збоях, тобто збоїв БІЛЬШЕ, ніж зроблених. Той самий клас —
    #     ранкова Фузовка: 10 шардів на V100 з рук, 338 з'їдених сторінок.
    #   · РОЗКЛАДКА Є (з 2026-08-11): `_start_shard` дає шарду k пристрій
    #     `cuda:(k % N)` і власний GPU-лок; перевірено — шарди чергуються по
    #     картах. Тоді ділити сумарну VRAM означало б утричі занизити
    #     8-карткову машину без жодної причини.
    #
    # Тому прапорець ЯВНИЙ, а не мовчазне припущення: він і є місце, де ці дві
    # частини системи домовляються. Міняти його можна лише разом із раннером.
    num_gpus = max(1, int(num_gpus or 1))
    # 🔴🔴 Шарди пакуються ПО КАРТАХ, а не в суму пам'яті: шард не ділиться між
    # картами. На 6 × GTX 1080 (8 ГБ) при 6 ГБ на шард сума давала
    # ⌊48 × 0.9 / 6⌋ = 7 шардів, а влазить рівно по одному на карту — 6.
    per_card = int((vram_gb / num_gpus) * headroom // gb_per_shard)
    shards_vram = per_card * num_gpus if shards_distributed else per_card
    # `cores_per_shard` менше за дефолт — перечитування на готовій сегментації:
    # шард не платить за геометрію й sato, і ядро тримає більше шардів.
    shards_cpu = int(cores // max(0.1, cores_per_shard or MIN_CORES_PER_SHARD))
    shards = min(shards_vram, shards_cpu, int(max_shards))

    if shards < 1:
        limited = "vram" if shards_vram < 1 else "cpu"
        return Sizing(0, 0, 0.0, cores, limited, 0.0)

    if shards == max_shards and shards < min(shards_vram, shards_cpu):
        limited = "cap"
    elif shards_vram <= shards_cpu:
        limited = "vram"
    else:
        limited = "cpu"

    # 🔴 Округлення, а не відкидання. З `floor` 26 ядер на 10 шардів давали по
    # 2 потоки, тобто 20 задіяних ядер із 26 — і модель передбачала, що
    # БІЛЬШЕ шардів дасть МЕНШЕ сторінок (1040 проти 1248 на восьми). Це не
    # властивість заліза, а артефакт цілочисельного ділення: планувальник
    # обирав би гіршу розкладку через власну арифметику.
    threads = max(1, min(MAX_THREADS_PER_SHARD, round(cores / shards)))
    # Оцінка ЗАЙНЯТОСТІ ядер і стеля потоків — різні числа. Стеля має бути
    # цілою і радше меншою (щоб BLAS не оверсабскрайбив), а зайнятість — це
    # просто «скільки ядер реально молотить»: N паралельних сторінок беруть
    # усе, до чого дотягнуться. Через `floor` в обох ролях модель вважала, що
    # 12 шардів на 26 ядрах задіють 24 ядра, а 8 шардів — 24 ж, і видавала
    # немонотонний прогноз.
    cores_used = min(
        cores,
        float(shards * min(MAX_THREADS_PER_SHARD, math.ceil(cores / shards))),
    )
    # 🔴 Три обмежувачі, і кожен — функція МАТЕРІАЛУ через спільний подільник
    # `L0 + рядки`. Без рядків (нуль) усі дають рівно ті самі числа, що й до
    # 06.09.2026.
    #
    # 🔴 Рахуємо в РЯДКО-ГОДИНАХ і ділимо ОДИН раз у кінці. Поділивши в кожному
    # доданку окремо, ми втрачаємо точну рівність на зламі (16 ядер на 8
    # шардах: 36 000×8 = 18 000×16) — вона розсипається на останньому ulp, і
    # приймач «ядра самі по собі темпу не купують» починає падати від
    # арифметики, а не від моделі.
    #
    # 🔴 Ядра діють ДВІЧІ, і це не те подвійне врахування, яке зняли 05.09:
    # вище вони ріжуть ЧИСЛО шардів (`shards_cpu`), тут — ставлять СПАДНУ
    # стелю темпу для випадку, коли шардів підняли більше, ніж є кому
    # годувати. Спростована стеля була зростаюча й піднімала прогноз; ця
    # ніколи не піднімає його вище за флотовий доданок.
    shard_lines = SHARD_LINES_PER_HOUR * shards
    card_lines = CARD_MAX_LINES_PER_HOUR * num_gpus
    core_lines = CORE_LINES_PER_HOUR * cores
    budget = min(shard_lines, core_lines, card_lines)
    lines = float(lines_per_page) if lines_per_page and lines_per_page > 0 \
        else LINES_PER_PAGE_DEFAULT
    pages_per_hour = budget / (fixed_cost_for(frame_mpx) + lines)
    # 🔴 `card_capped` лишається суворо про КАРТУ. Зробити з нього «щось
    # тисне» означало б показувати стелю карти там, де бокс просто без ядер.
    card_capped = card_lines <= budget
    cpu_capped = core_lines < min(shard_lines, card_lines)
    return Sizing(
        shards=shards,
        threads_per_shard=threads,
        cores_used=cores_used,
        wasted_cores=max(0.0, cores - cores_used),
        limited_by=limited,
        pages_per_hour=pages_per_hour,
        card_capped=card_capped,
        cpu_capped=cpu_capped,
    )


def predict_hours(pages: int, sizing: Sizing, *, warm: bool = False,
                  cases: int = 1, boot_sec: float = 0.0) -> float:
    """Годин на ВЕСЬ захід: підйом, черга справ, транспорт і саме читання.

    `cases` — скільки справ у черзі. 🔴 Без нього прогноз рахував лише разовий
    холодний старт, тож черга з 237 мікросправ виглядала не дорожчою за чергу
    з однієї — а насправді віддала накладним 55% рахунку.

    `boot_sec` — ЗАМІРЯНИЙ на цій машині підйом (рахується від оренди до
    робочого SSH). 🔴🔴 Без нього прогноз давав усім однакові 5 хвилин холодного
    старту, тоді як хост тягне образ СВОЇМ каналом: 23.09.2026 бокс у Кореї
    піднімався **27 хвилин** — у п'ять разів понад сталу, і це чистий
    оплачений `docker pull`, а не робота. Реєстр цей час пам'ятав і навіть
    пояснював («єдиний сигнал про закешованість образу»), але у РОЗРАХУНОК він
    не йшов — тобто машину, про яку ми знаємо, що вона підніматиметься пів
    години, скоринг бачив як будь-яку іншу.

    `inf`, якщо залізо непридатне — так воно чесно вилітає з будь-якого
    порівняння з `max_hours`, а не вдає нуль.
    """
    if not sizing.usable:
        return math.inf
    n_pages = max(0, int(pages))
    overhead = (float(boot_sec) if boot_sec and boot_sec > 0
                else float(OVERHEAD_SEC_WARM if warm else OVERHEAD_SEC_COLD))
    overhead += max(1, int(cases)) * PER_CASE_SEC
    overhead += n_pages * PER_PAGE_OVERHEAD_SEC
    return n_pages / sizing.pages_per_hour + overhead / 3600.0


def predict_cost(pages: int, sizing: Sizing, dph: float, *, warm: bool = False,
                 cases: int = 1, boot_sec: float = 0.0) -> float:
    """Скільки коштуватиме ВЕСЬ захід на цій машині, $ — з накладними."""
    hours = predict_hours(pages, sizing, warm=warm, cases=cases, boot_sec=boot_sec)
    if math.isinf(hours):
        return math.inf
    return hours * max(0.0, float(dph))
