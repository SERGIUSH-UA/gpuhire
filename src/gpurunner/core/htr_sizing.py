#: Стеля ОДНІЄЇ КАРТИ, рядко-еквівалентів за годину. Замір std160 на RTX 3090:
#: 12 шардів × 420 на шард × 99 (29+70) ≈ 16 шардів × 312 × 99 ≈ 495 000 —
