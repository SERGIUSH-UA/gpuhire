#: ── Фіксована ціна сторінки за ПЛОЩЕЮ КАДРУ (23.09.2026) ─────────────────────
#: `LINES_FIXED_COST = 40` — ціна сегментації СЕРЕДНЬОГО кадру нашої історії
#: (~12 Мпікс). На легких кадрах вона менша, на розворотах більша, і доки площа
#: в прогноз не входила, модель стискала різницю між матеріалами: spr-60
#: (3 Мпікс, 22 рядки) читалась 2.2 с/стор на шард при прогнозі 6.9.
#:
#: Підгонка по 59 справах із пошторінковим часом (`_htr_meta.json`, поле `sec`)
#: і справжнім числом шардів: `L0 = 16 + 2 × Мпікс`. На 12 Мпікс це рівно 40 —
#: тобто там, де площа невідома (0), прогноз не рухається, і приймачі
#: калібровки на 457 заходах лишаються чинними.
FIXED_COST_BASE = 16.0
FIXED_COST_PER_MPX = 2.0


def fixed_cost_for(frame_mpx: float = 0.0) -> float:
    """`L0` у рядко-еквівалентах: ціна сторінки поза рядками, від площі кадру."""
    if not frame_mpx or frame_mpx <= 0:
        return LINES_FIXED_COST
    return FIXED_COST_BASE + FIXED_COST_PER_MPX * float(frame_mpx)


def per_shard_pages_per_hour(lines_per_page: float = 0.0) -> float:
    """Темп одного шарда на матеріалі з такою щільністю рядків."""
    lines = float(lines_per_page) if lines_per_page and lines_per_page > 0 \
        else LINES_PER_PAGE_DEFAULT
    return SHARD_LINES_PER_HOUR / (LINES_FIXED_COST + lines)


def card_cap_pages_per_hour(lines_per_page: float = 0.0) -> float:
    """Стеля однієї карти на цьому матеріалі."""
    lines = float(lines_per_page) if lines_per_page and lines_per_page > 0 \
        else LINES_PER_PAGE_DEFAULT
    return CARD_MAX_LINES_PER_HOUR / (LINES_FIXED_COST + lines)


def core_cap_pages_per_hour(cores: float, lines_per_page: float = 0.0) -> float:
    """Стеля, яку ставлять ЯДРА: шард на повний темп виходить із двох.

    Ядра понад дві на шард темпу не купують — це і є висновок дуелі 05.09; тут
    ловиться протилежний випадок, коли шардів підняли більше, ніж є кому
    годувати.
    """
    lines = float(lines_per_page) if lines_per_page and lines_per_page > 0 \
        else LINES_PER_PAGE_DEFAULT
    return CORE_LINES_PER_HOUR * max(0.0, float(cores)) / (LINES_FIXED_COST + lines)


#: 🔴 Шард бере ~ОДНЕ ядро, а не два. Замір std160 05.09.2026 (RTX 3090, квота
#: 11.52 ядра): 12 шардів — loadavg 10.2, 5040 стор/год; 16 шардів — 10.8 і
#: 4997 (уперлись у карту, не в ядра). Стара «2 ядра/шард» (Beam, 38.3 с/стор)
#: мірялась без `_limit_own_threads`: кожен шард розгортав BLAS на весь хост
#: і душив сусідів — то була вада потоків, а не апетит шарда. Ціна старої
#: сталої на тому самому боксі: 5 шардів замість 12, тобто −40% темпу.
#: ⚙ 21.09.2026: одне ядро ЗАПУСКАЄ шард (це число), але на ПОВНИЙ темп шард
#: виходить із двох (`CORES_PER_SHARD_FULL_RATE`). Різниця не словесна: 12
#: шардів на 11.5 ядрах справді працюють і швидше за 5, тож тут лишається 1 —
#: а те, що вони при цьому не дають дванадцяти повних темпів, тепер сказано
#: там, де воно правдиве, тобто в темпі.
MIN_CORES_PER_SHARD = 1.0

#: Стеля потоків BLAS/OpenMP на шард. 🔴 Без явного обмеження чотири шарди на
#: хості з 255 ядрами розгорнули 182 потоки при квоті контейнера 8 — і
#: задушили самі себе.
MAX_THREADS_PER_SHARD = 8


#: 🔴🔴 ПАМ'ЯТЬ ШАРДА РОСТЕ З РЯДКІВ У БАТЧІ, А НЕ З ПЛОЩІ КАДРУ. Це головне
#: тут, і саме на цьому вже двічі помилялись у протилежні боки.
#:
#: Базове споживання шарда — 3.2-3.6 ГБ ЗАВЖДИ: це ваги PARSeq + kraken і
#: буфери, вони не залежать ні від матеріалу, ні від стелі сегментації.
#: **Робоче число — 3.3**, і воно виміряне, а не виведене.
#:
#: 🔴 Дефолтні 2.5 стоять НИЖЧЕ базового споживання — тобто вони не «компроміс»,
#: а гарантований OOM на щільному аркуші: 8 шардів × 3.3 = 26 ГБ на 24-ГБ карті
#: дали 62% сторінок у збоях (12.08.2026, ANRM).
#:
#: 🔴 Але й запас брати НЕ МОЖНА — він коштує грошей мовчки. Завищений поріг
#: міняє не лише число шардів на обраній машині: скоринг рахує
#: `шарди = вільна VRAM × 0.9 ÷ поріг` ще на РАНЖУВАННІ РИНКУ, тож захід
#: систематично їде на гіршу машину. Замір 19.08.2026 (ДАВО ф.337, розворот):
#:
#: | поріг | машина | шардів | темп | ціна |
#: |---|---|---|---|---|
#: | 4.5 «за площею» | RTX 4060 Ti, 16 ядер | 3 | 538 стор/год | $0.10 |
#: | **3.3** | **RTX 3090, 64 ядра** | **7** | **1750 стор/год** | **$0.10** |
#:
#: Утричі швидше за ті самі гроші. Ось чому масштабувати поріг «за площею
#: кадру» — арифметика не з тієї величини: розворот множить ПЛОЩУ, але не
#: щільність рядків (у подворних списках їх ~50-80 на кадр, тобто вдвічі менше,
#: ніж у сповідці на тій самій площі).
#:
#: 🔴 Сірий колір пам'яті теж майже не економить — рушій усе одно бінаризує.
#:
#: Що робити з матеріалом, який справді важчий за 3.3: НЕ вгадувати наперед, а
#: піднімати за фактом — при повторному `fleet_dying` з OOM наглядач сам додає
#: крок і переорендовує (`Supervisor._bump_gb_per_shard`). Ціна помилки в цей
#: бік обмежена одним циклом; ціна запасу — кожна оренда заходу.
GB_PER_SHARD = 3.3

#: 🔴 Перемiряно 05.09.2026 (std160, RTX 3090, кадри 7.2 Мпікс): 12 шардів
#: зайняли 14.8 ГБ, 16 — 17.8, тобто 1.1–1.25 ГБ на шард на ЛЕГКИХ кадрах.
#: «3.2–3.6 завжди» було правдою для 16-Мпікс розворотів, де пік іде від
#: найбільшого кадру в алокаторі торча. Підлога — з запасом над заміром.
#:
#: 🔴🔴 ПЕРЕМІРЯНО 23.09.2026 — і ця формула виявилась головним обмежувачем
#: ринку. На знімку ринку 23.09 КОЖНА машина, що могла б дати 5 000 стор/год,
#: упиралась у VRAM (`limited_by="vram"`): при 2.72 ГБ на шард (12 Мпікс за
#: старою формулою) ціль проходила 0–1 машина зі 198, при ~1.6 — 12–17.
#:
#: Заміряне ЗАЙНЯТТЯ КАРТИ на шард (`card_used_max_mb / шарди`, стан сесій
#: після нового раннера 04.09 і розкладки по картах 11.08), OOM — нуль на всіх
#: 30 записах `shard_calibration.jsonl`:
#:
#:   | Мпікс | справа | ГБ карти на шард |
#:   |---|---|---|
#:   | 5.5–6.8 | spr-43, spr-54 (Q8000, 10 шардів) | 0.4–0.6 |
#:   | 11.6–12 | spr-47а (2080 Ti, 14), 2389659 (TITAN X, 6) | 0.9–1.3 |
#:   | 18.6–23 | spr-772, 442, 576, 705, 188, 203b | 0.5–2.0 |
#:
#: Верхня межа — ~0.4 + 0.08 × Мпікс; беремо 0.6 + 0.08 × Мпікс (запас +0.2).
#: Старі точки «16 Мпікс → 3.3» (ANRM, 12.08) — це заповнена алокатором
#: карта ДО розкладки шардів по картах і нового раннера, а не потреба шарда.
#:
#: 🔴 Помилку в бік «замало» ловить не цей прогноз, а регулятор на боксі: він
#: росте лише за ВИМІРЯНИМ зайняттям карти, а на OOM і тиску (>95%) сам
#: стискає флот (`_regulate_decision` у раннері) без переоренди.
GB_PER_SHARD_FLOOR = 1.0
GB_PER_SHARD_BASE = 0.6
GB_PER_MPX = 0.08
#: Вище — вже не розкладка: один шард на карту.
GB_PER_SHARD_CEILING = 6.0

#: 🔴🔴 СТАРТ флоту на боксі — за СТАРОЮ, перевіреною формулою, а не за
#: реалістичною вище. Два числа свідомо різні, бо ціна помилки в два боки різна:
#:
#: - вибір машини питає, СКІЛЬКИ машина здатна дати, — і там завищена пам'ять
#:   шарда відрізала ринок цілком (0–1 машина з 198 на 12 Мпікс);
#: - старт питає, скільки шардів підняти НАОСЛІП, до першого заміру карти, — і
#:   там занижена пам'ять коштує сторінок: 04.09.2026 сірі кадри на 2.5 ГБ дали
#:   141 збій зі 191 спроби. Калібровка починається саме з того дня, тож її
#:   «нуль OOM» — це «ми більше туди не потрапляли», а не «туди не потрапити».
#:
#: Вгору від старту флот веде регулятор раннера — лише за ВИМІРЯНИМ зайняттям
#: карти, із запасом на пік; стелю йому дає `fleet_ceiling` наглядача. Не
#: виріс до обіцяного — це ловить звірка темпу з обіцянкою під час заходу.
GB_PER_SHARD_START_FLOOR = 1.8
GB_PER_SHARD_START_BASE = 0.8
GB_PER_MPX_START = 0.16


def gb_per_shard_start_for(frame_mpx: float = 0.0) -> float:
    """Пам'ять шарда для СТАРТУ флоту на боксі (до першого заміру карти)."""
    if not frame_mpx or frame_mpx <= 0:
        return GB_PER_SHARD
    return max(GB_PER_SHARD_START_FLOOR,
               min(GB_PER_SHARD_CEILING,
                   GB_PER_SHARD_START_BASE + GB_PER_MPX_START * float(frame_mpx)))


def gb_per_shard_for(frame_mpx: float = 0.0, aspect: float = 0.0) -> float:
    """Скільки VRAM просити на шард на кадрах такої площі.

    Нуль (не міряли) → `GB_PER_SHARD`: невідомий матеріал вважається важким,
    бо ціна помилки в бік «замало» — OOM і збої, а в бік «забагато» — лише
    менший флот. Aspect навмисно НЕ впливає: рядки з форми кадру не виводяться
    (розворот-список має їх удвічі менше, ніж сповідка тієї самої площі), а
    пам'ять шарда росте з ПЛОЩІ кадру — це і є те, що міряє `frame_mpx`.

    ⚠ Це не скасовує уроку 19.08.2026 («4.5 за площею» → втричі повільніший
    захід): тоді поріг ПІДНІМАЛИ за площею понад базу, тут його ОПУСКАЮТЬ до
    заміряного на легких кадрах, а на 16 Мпікс він і лишається ~3.3.
    """
    if not frame_mpx or frame_mpx <= 0:
        return GB_PER_SHARD
    return max(GB_PER_SHARD_FLOOR,
               min(GB_PER_SHARD_CEILING, GB_PER_SHARD_BASE + GB_PER_MPX * float(frame_mpx)))


#: Лишаємо карті запас: драйвер, кеш алокатора, фрагментація на хвості.
VRAM_HEADROOM = 0.90

