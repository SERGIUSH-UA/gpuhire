"""Що робити просто зараз: єдина функція рішень наглядача.

Уся логіка «чекати / забрати / доганяти / переорендувати / гасити» зведена в
одну **чисту** функцію. Причина проста: це саме те місце, де раніше рішення
ухвалював агент — очима, з логів, і з затримкою в години. Функцію можна
ганяти таблицею сценаріїв за мілісекунди й без жодного орендованого боксу.

Порядок правил — не косметика. Спершу перевіряється те, що коштує гроші
просто зараз (мертвий бокс, дедлайн, бюджет), і лише потім — те, що коштує
роботу (неповнота, черга).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

Action = Literal[
    "price_alert",
    "destroy_overpriced",  # ціна сторінки тримається вище стелі — гасимо
    "wait",              # усе гаразд, наступний тік
    "fetch_and_finish",  # справа готова → забрати, звірити, погасити
    "next_case",         # готова, але черга не порожня → теплий бокс
    "catchup",           # сторінок бракує → доганяти на живому боксі
    "rerent",            # раннер помер, бокс живий → підняти з чекпоінтів
    "destroy_dead_box",  # бокс не відповідає
    "destroy_budget",    # гроші скінчились
    "destroy_deadline",  # час скінчився
    "startup_failed",    # бокс живий, робота не почалась — інша машина не поможе
]

#: Стани інстансу, у яких він уже нічого не рахує.
DEAD_STATES = frozenset({"exited", "offline", "stopped", "gone", "destroyed", "error"})


#: Фази, у яких шарди ще/уже не працюють, а раннер має посуватись сам:
#: до першого прогресу (порожньо), старт справи, качання й розпакування кадрів.
SETUP_PHASES = ("", "starting", "downloading", "unpacking")


@dataclass(frozen=True)
class Cfg:
    """Межі заходу. Бюджет і строк — єдині, що не послаблюються ніколи."""

    budget_usd: float
    max_hours: float
    #: Скільки терпіти мовчання `_progress.json` при живому SSH. Раннер пише
    #: його кожні 10 с, тож 20 хвилин тиші — це смерть раннера, а не пауза.
    stale_progress_sec: int = 1200
    #: 🔴 Скільки чекати ПЕРШОГО прогресу після оренди.
    #:
    #: Окреме число, бо це окрема хвороба. Бокс може бути живий, залізо
    #: здорове, SSH бездоганний — і при цьому не рахувати НІЧОГО: не доїхали
    #: моделі (порожня shell-змінна в посиланні), не розпакувався архів,
    #: упав pip. Ззовні це не відрізнити від «ще стартує», і саме тому
    #: коштує дорого: машина оплачується, поки хтось не гляне очима.
    #:
    #: 12 хвилин = pip (до 3) + assets (до 2) + кадри (до 5) із запасом.
    first_progress_sec: int = 720
    #: Скільки провалів SSH поспіль вважати смертю боксу (тік ~30 с → ~1.5 хв).
    ssh_fail_streak_max: int = 3
    #: Те саме, але коли раннер УЖЕ відзвітував `done`/`failed`. На боксі лежить
    #: готовий результат, тож гасити його через транзієнтний флап каналу —
    #: найдорожча з можливих помилок: платимо вдруге за вже зроблене.
    ssh_fail_streak_max_done: int = 20
    #: Скільки тіків поспіль `_progress.json` має бути нечитаним, перш ніж
    #: оголошувати, що робота не почалась. 🔴 Один транзієнт (OSError на
    #: `sftp.open`, гонка з `os.replace` під час запису) давав ТЕРМІНАЛЬНИЙ
    #: вердикт і знищення боксу — при тому, що для SSH-збоїв лічильник серії
    #: був, а для цієї, дорожчої, гілки не було.
    progress_miss_streak_max: int = 3
    #: Стеля ціни тисячі сторінок для перевірки НА ХОДУ. Те саме число, що в
    #: `offer_score.MAX_USD_PER_1000_PAGES`, але там воно про прогноз, а тут —
    #: про факт.
    max_usd_per_1000: float = 0.20
    #: 🔴 Скільки ціна сторінки має ТРИМАТИСЬ вище стелі, перш ніж гасити.
    #:
    #: Просто «вище стелі» тут не годиться: темп на живому боксі стрибає —
    #: важкий аркуш, збіг качання наступної справи, вотчдог піднімає шард. Одна
    #: така просадка не є станом машини, і гасити по ній означає викинути вже
    #: оплачену роботу. Гасимо, коли перевищення ВИСТОЯЛОСЬ: і за часом, і за
    #: числом тіків поспіль (тік ~30 с, тож 900 с — це ~30 послідовних замірів,
    #: а не три сусідні).
    #:
    #: Заміряно 2026-08-19 на машині 139040 (чужий процес тримав 19 з 24 ГБ):
    #: $0.953 → $0.965 → $0.976 за 1000 при стелі $0.20 — трималось усі
    #: пів години, поки не втрутилась людина.
    price_breach_grace_sec: int = 900
    price_breach_streak_max: int = 3
    #: 🔴 Приймач грошей на оренду: через `min_age` після ДОЗРІВАННЯ темпу
    #: фактична ціна тисячі (гроші оренди ÷ її сторінки, обидва від тієї мити)
    #: не сміє перевищувати `tolerance` × найкращу ціну, яку цей бокс показував
    #: сам. 20 хв — щоб одна важка справа чи перехід між справами не рахувались
    #: як переплата; 2× — бо година зависання після години роботи рівно
    #: подвоює ціну, а просадка на важкому аркуші до двох не доходить.
    rent_price_min_age_sec: int = 1200
    rent_price_tolerance: float = 2.0
    #: Частка збоїв, вище якої флот вважається таким, що вмирає, і скільки
    #: тіків поспіль вона має протриматись.
    fail_ratio_max: float = 0.25
    fail_streak_max: int = 2
    #: 🔴 МІНІМАЛЬНИЙ ЗНАМЕННИК. Частка нічого не означає на кількох спробах:
    #: на відновленій справі `fresh` дорівнює нулю (усе підняте з чекпоінтів),
    #: тож ОДНА невдала сторінка дає рівно 100% — і наглядач гасив СПРАВНИЙ
    #: бокс. Заміряно 2026-08-22 на ЦДІАК ф.224 (41 справа): три оренди поспіль
    #: закрилися вердиктом «100% спроб у збоях (1 сторінок)», хоча в лозі
    #: раннера обидва шарди щоразу віддавали `rc=0` за 10 с, а незробленою
    #: лишалась одна сторінка, вже КАРАНТИНОВАНА попереднім заходом.
    fail_min_attempts: int = 10
    #: Скільки терпимо ТИШУ під час сетапу (фаза не `running`): pip, завантаження
    #: ассетів і кадрів, розпакування. Окрема, значно більша стеля, бо в цій
    #: фазі раннеру нічого публікувати за побудовою.
    setup_max_sec: int = 3600
    #: 🔴 Скільки терпимо сетап, який НЕ ПОСУВАЄТЬСЯ. Стеля вище — про час,
    #: ця — про рух: лог раннера мусить рости, поки йде pip, качання й
    #: розпакування. Виміряно 17.08.2026 на ф.230: бокс завис на качанні
    #: 412-МБ архіву й простояв 50 хвилин, а стан увесь цей час казав
    #: `ssh_ok: true`, `human_action_required: false` — тобто мовчав рівно
    #: доти, доки хтось не подивився очима. Годинна стеля його не спіймала б
    #: узагалі, бо 50 < 60.
    #:
    #: Той самий принцип, що вже стоїть на очікуванні SSH і на трьох таймерах
    #: хоста: дивитись на ПОСУВАННЯ, а не на секундомір.
    setup_stall_sec: int = 900
    #: 🔴 Скільки щойно орендований бокс має право «не існувати».
    #:
    #: `GET /instances/<id>/` віддає порожньо ще кілька хвилин після оренди —
    #: інстанс просто не встиг з'явитись у видачі. Наш код читав це як `gone`
    #: і на ПЕРШОМУ Ж тіку казав `destroy_dead_box`. Звідси весь цикл
    #: 2026-08-11: чотири інстанси, кожен прожив ~1 хвилину, жоден не встиг
    #: навіть спробувати працювати.
    fresh_rent_grace_sec: int = 300
    #: Запас, який лишаємо на забір результату й гасіння.
    reserve_usd: float = 0.05


@dataclass(frozen=True)
class Obs:
    """Усе, що наглядач знає в цю мить. Нічого, крім цього, `decide` не бачить."""

    progress: dict | None = None
    progress_age_sec: float = 0.0
    ssh_ok: bool = True
    ssh_fail_streak: int = 0
    progress_miss_streak: int = 0
    #: Остання ВІДОМА фаза (з попереднього успішного читання). Переживає обрив
    #: SSH — саме тому вона тут окремо від `progress`.
    last_phase: str = ""
    instance_state: str = "running"
    spent_usd: float = 0.0
    dph: float = 0.0
    elapsed_h: float = 0.0
    queue_left: int = 0
    catchup_rounds_done: int = 0
    catchup_passes: int = 2
    #: Скільки тіків поспіль і скільки часу ціна тисячі сторінок тримається
    #: вище стелі. Рахує наглядач; перший же тік у межах стелі обнуляє обидва.
    price_breach_streak: int = 0
    price_breach_sec: float = 0.0
    #: Скільки тіків поспіль частка збоїв вище `fail_ratio_max`.
    fail_streak: int = 0
    #: Скільки секунд лог раннера НЕ РОСТЕ (тільки для фази сетапу).
    setup_stall_sec_seen: float = 0.0
    #: Скільки тіків поспіль половина флоту лежить із ненульовим rc. Окремий
    #: лічильник, а не спільний із `fail_streak`: шард може впасти й БЕЗ збоїв
    #: на сторінках (OOM у сегментації, вбитий вотчдогом, помилка середовища).
    dead_streak: int = 0
    #: Скільки живе ПОТОЧНА оренда. Правила смерті боксу до цього віку не
    #: застосовуються — див. `Cfg.fresh_rent_grace_sec`.
    rent_age_sec: float = 1e9
    #: Гроші, що пішли на ПОТОЧНУ оренду, і сторінки, які вона реально дала
    #: (не самозвіт раннера, а лічильник наглядача по прогресу цього боксу) —
    #: обидва ВІД МИТІ, коли темп цього боксу дозрів, і скільки від неї минуло.
    #: 🔴 Не від створення інстансу: сетап (pip, качання кадрів) і розгін
    #: регулятора роздували ціну вдвічі, і правило 3-тер гасило здорові бокси
    #: (904-24-70, 11.09.2026: живі $0.078 за 1000, «за орендою» $0.140).
    rent_usd: float = 0.0
    rent_pages: int = 0
    rent_settled_sec: float = 0.0
    #: Найкраща ціна тисячі, яку цей бокс показав на дозрілому темпі. Нуль =
    #: ще невідомо, і тоді правило 3-тер мовчить.
    box_best_usd_per_1000: float = 0.0

    # ---- зручні витяги з прогресу ----

    @property
    def phase(self) -> str:
        return str((self.progress or {}).get("phase") or "")

    #: Скільки сторінок у ВСІЙ черзі й скільки з неї вже позаду (справи, що
    #: завершились раніше). Без цього прогноз витрат систематично оптимістичний:
    #: `n_pages_expected` у прогресі — посправна, тож на черзі з дев'яти справ
    #: наглядач бачив хвіст однієї й дізнавався про перевитрату аж на жорсткому
    #: порозі «витрачено ≥ бюджет», де на забір уже нічого не лишалось.
    queue_pages_total: int = 0
    queue_pages_before: int = 0

    @property
    def cases_left(self) -> int:
        """Скільки справ черги ще попереду, рахуючи поточну як пройдену.

        Потрібно рівно для одного: розгін (старт шардів, ваги, качання кадрів)
        повторюється на КОЖНІЙ справі, і прогноз мусить його додати стільки
        разів, скільки їх лишилось.
        """
        p = self.progress or {}
        try:
            total = int(p.get("cases_total") or 1)
            index = int(p.get("case_index") or 1)
        except (TypeError, ValueError):
            return 0
        return max(0, total - index)

    @property
    def pages_skipped(self) -> int:
        return int((self.progress or {}).get("pages_skipped") or 0)

    @property
    def pages_left(self) -> int:
        """Скільки сторінок ще НЕ мають тексту.

        🔴 `pages_done` рахує лише прочитане ЦИМ проходом і НЕ включає
        пропущених — а пропущена сторінка це та, у якої текст на диску вже є:
        шард побачив його й пішов далі. Пропуски з'являються щоразу, коли
        вотчдог перепідіймає завислий шард, тобто в нормальному житті прогону.

        Ціна недоліку виміряна: залишок завищувався на число пропущених,
        прогноз витрат (`spent + залишок / темп × ціна`) роздувався слідом, і
        `budget_stop` гасив ЗДОРОВИЙ прогін. У звітах цей лічильник названо
        брехливим щонайменше п'ять разів.

        ⚠ Підняте з чекпоінтів (`pages_resumed`) уже сидить у `pages_done`, і
        воно ж пізніше з'явиться в пропущених, коли шард дійде до тих сторінок.
        Тому сума обмежена знаменником: подвійний рахунок може лише применшити
        залишок, а це безпечний бік — витрати однаково стереже ФАКТИЧНА
        сплачена сума, тоді як завищений залишок убиває робочий бокс.
        """
        p = self.progress or {}
        expected = int(p.get("n_pages_expected") or 0)
        done = int(p.get("pages_done") or 0) + self.pages_skipped
        if expected:
            done = min(expected, done)
        left_here = max(0, expected - done)
        if self.queue_pages_total:
            left_queue = max(0, self.queue_pages_total - self.queue_pages_before - done)
            return max(left_here, left_queue)
        return left_here

    @property
    def pages_per_hour(self) -> float:
        return float((self.progress or {}).get("pages_per_hour") or 0.0)

    @property
    def pages_done(self) -> int:
        return int((self.progress or {}).get("pages_done") or 0)

    @property
    def work_sec(self) -> float:
        """Скільки шарди РЕАЛЬНО працюють (раннер рахує від їхнього старту)."""
        return float((self.progress or {}).get("wall_sec") or 0.0)

    @property
    def usd_per_1000(self) -> float:
        """Скільки коштує тисяча сторінок ЗА ФАКТОМ, а не за обіцянкою."""
        if self.pages_per_hour <= 0 or self.dph <= 0:
            return 0.0
        return self.dph / (self.pages_per_hour / 1000.0)

    @property
    def throughput_settled(self) -> bool:
        """Чи дозрів вимір темпу настільки, щоб на ньому щось будувати.

        Дві умови разом, і обидві потрібні: досить прочитаних сторінок (одна
        повільна не спотворює середнє) І досить часу роботи ШАРДІВ, а не
        оренди — бо між орендою й першою сторінкою лежать качання архіву,
        розпакування і pip, під час яких темп чесно дорівнює нулю.
        """
        # 🔴 Рахуються сторінки, прочитані САМЕ ЦИМ боксом. `pages_done` несе
        # ще й підняті з чекпоінтів, тож на відновленій справі половина воріт
        # була виконана з першого тіку: після переоренди з 2000 відновлених
        # сторінок вистачало трьох нових за 15 хв, щоб темп «дозрів» на рівні
        # 12 стор/год — і бюджетний прогноз гасив бокс саме тоді, коли вотчдог
        # уже піднімав завислий шард.
        p = self.progress or {}
        fresh = self.pages_done - int(p.get("pages_resumed") or 0)
        return fresh >= WARMUP_PAGES and self.work_sec >= WARMUP_SEC

    @property
    def pages_failed(self) -> int:
        return int((self.progress or {}).get("pages_failed") or 0)

    @property
    def oom_events(self) -> int:
        return int((self.progress or {}).get("oom_events") or 0)

    @property
    def shards_total(self) -> int:
        return len((self.progress or {}).get("shards") or [])

    @property
    def shards_alive(self) -> int:
        return sum(1 for sh in ((self.progress or {}).get("shards") or [])
                   if sh.get("alive"))

    @property
    def shards_dead(self) -> int:
        """Шарди, що ВПАЛИ, — а не ті, що дочитали свою частину й вийшли.

        🔴🔴 `alive` у раннері означає рівно `rc is None`, тобто «процес ще
        живий». Шард, який доробив свій зріз, виходить із `rc=0` і стає
        `alive: false` — це НОРМА, кінець роботи. Перша версія правила рахувала
        саме `alive` і тому на хвості кожної справи бачила «флот обсипався» при
        нулі збоїв: 2026-08-19 це тричі поспіль погасило здорові бокси
        («живих шардів 1 із 2 … збоїв 0») і спалило шість оренд поспіль.

        Смерть — це НЕНУЛЬОВИЙ `rc`. Вотчдог раннера сам піднімає впалий шард і
        скидає `rc` у `None`, тож сюди потрапляє лише те, що він уже здав.
        """
        dead = 0
        for sh in (self.progress or {}).get("shards") or []:
            # 🚰 Злитий шард погасив сам регулятор. Старий раннер при цьому
            # повертав rc=3, і звуження флоту читалось би як його смерть.
            if sh.get("draining"):
                continue
            rc = sh.get("rc")
            if rc is not None and int(rc) != 0:
                dead += 1
        return dead

    @property
    def fail_ratio(self) -> float:
        """Частка спроб, що завершились збоєм, на СВІЖІЙ роботі цього боксу.

        🔴 Знаменник — свіжі сторінки плюс збої, а не `pages_done`: останнє
        несе ще й підняте з чекпоінтів, тож на відновленій справі будь-яка
        частка виглядала б мізерною саме тоді, коли флот сиплеться.
        """
        return (self.pages_failed_active / self.fail_attempts
                if self.fail_attempts else 0.0)

    @property
    def pages_quarantined(self) -> int:
        """Скільки сторінок раннер уже визнав безнадійними і БІЛЬШЕ НЕ ПРОБУЄ."""
        return int((self.progress or {}).get("quarantined") or 0)

    @property
    def pages_failed_active(self) -> int:
        """Збої, які ще щось означають про стан флоту.

        🔴 Карантинована сторінка не буде спробувана НІКОЛИ (`_htr_quarantine.json`
        переживає resume), тож вона назавжди сидить у чисельнику й тримає частку
        на стелі — навіть коли флот здоровий і решту справи вже дораховано.
        """
        return max(0, self.pages_failed - self.pages_quarantined)

    @property
    def fail_attempts(self) -> int:
        """Знаменник частки збоїв: свіжі сторінки цього боксу плюс живі збої.

        🔴 `pages_resumed` віднімається, бо підняте з чекпоінтів не є роботою
        ЦЬОГО боксу — інакше на відновленій справі будь-яка частка виглядала б
        мізерною саме тоді, коли флот сиплеться.
        """
        p = self.progress or {}
        fresh = max(0, self.pages_done - int(p.get("pages_resumed") or 0))
        return fresh + self.pages_failed_active

    @property
    def missing_count(self) -> int:
        p = self.progress or {}
        return int(p.get("missing_count") or len(p.get("missing") or []))

    @property
    def steady_pages_per_hour(self) -> float:
        """Темп СТАЛОГО ходу: замір флоту у вікні, без розгону в знаменнику.

        🔴🔴 `pages_per_hour` раннера — це сторінки ÷ увесь час від старту
        шардів, тобто разом зі стартом семи процесів, завантаженням ваг і
        прогрівом. Регулятор поруч міряє інше: темп у вікні, яке відкривається
        після заспокоєння флоту (`rates {n: стор/год}` для поточного числа
        шардів). Обидва числа лежать в одному прогресі й розходяться вдвічі.

        21.09.2026 бюджетна гілка взяла гірше з двох: «за виміряним темпом
        (371 стор/год) вийде $0.57 при бюджеті $0.50» — при `rates {"7": 758}`
        у тому ж файлі. Захід спинився, а перезапуск на ТІЙ САМІЙ машині
        прочитав усю чергу за 32 хвилини і $0.151.

        Нуль — вікно ще не дозріло або флот щойно змінив число шардів.
        """
        reg = (self.progress or {}).get("regulator") or {}
        rates = reg.get("rates") or {}
        active = reg.get("active")
        if not rates or not active:
            return 0.0
        try:
            return float(rates.get(str(int(active))) or 0.0)
        except (TypeError, ValueError):
            return 0.0

    @property
    def case_overhead_sec(self) -> float:
        """Скільки секунд цієї справи пішло НЕ в читання, за фактом.

        Різниця між стінним часом шардів і тим, що пояснює сталий темп:
        качання архіву кадрів, розпакування, старт процесів, завантаження
        ваг. Кожна наступна справа черги заплатить це знову, тож прогноз без
        цього доданка занижує час — і рівно настільки, наскільки сталий темп
        вищий за середній.
        """
        steady = self.steady_pages_per_hour
        if steady <= 0 or self.work_sec <= 0:
            return 0.0
        read_sec = 3600.0 * self.pages_done / steady
        return max(0.0, self.work_sec - read_sec)

    def projected_total_usd(self) -> float:
        """Скільки вийде разом, якщо темп збережеться.

        🔴 Темп береться ВИМІРЯНИЙ (із живого прогресу), а не прогнозований
        при виборі оффера. Прогноз уже один раз збрехав — саме він дозволив
        узяти машину, що не встигала.

        🔴🔴 Але вимірів два, і вони про різне: сталий хід (`rates` флоту)
        показує, як швидко читається сторінка, а розгін (старт шардів, ваги,
        качання наступної справи) повторюється на КОЖНІЙ справі черги. Тому
        прогноз складається з обох: сторінки ділимо на сталий темп, а розгін
        додаємо стільки разів, скільки справ іще попереду. Середній темп
        робив те саме одним множенням — і тим розмазував розгін першої справи
        на всю чергу, завищуючи прогноз удвічі (21.09.2026, $0.57 проти
        фактичних $0.151).
        """
        if self.pages_left <= 0 or self.dph <= 0:
            return self.spent_usd
        steady = self.steady_pages_per_hour
        if steady > 0:
            hours_left = self.pages_left / steady
            hours_left += self.case_overhead_sec * self.cases_left / 3600.0
        elif self.pages_per_hour > 0:
            hours_left = self.pages_left / self.pages_per_hour
        else:
            return self.spent_usd
        return self.spent_usd + hours_left * self.dph


#: Скільки сторінок і секунд РОБОТИ ШАРДІВ треба, щоб вірити темпу.
#: 60 сторінок при типових 2000 стор/год — це близько двох хвилин справжнього
#: рахунку; 900 с покривають качання кількагігабайтного архіву й pip.
WARMUP_PAGES = 60
WARMUP_SEC = 900.0


def decide(obs: Obs, cfg: Cfg) -> tuple[Action, str]:
    """Дія і причина людською мовою. Причина йде і в стан, і у звіт."""

    # ── 1. бокс мертвий ────────────────────────────────────────────────────
    # 🔴 Свіжа оренда має грейс: перші хвилини Vast ще не показує інстанс у
    # видачі, а SSH законно не відповідає, поки хост тягне образ. Без цього
    # правила щойно взятий бокс оголошувався мертвим на першому ж тіку.
    fresh = obs.rent_age_sec < cfg.fresh_rent_grace_sec
    if not fresh:
        if obs.instance_state.lower() in DEAD_STATES:
            return "destroy_dead_box", (
                f"інстанс у стані «{obs.instance_state}» — він більше нічого не рахує, "
                f"але за нього досі платимо"
            )
        # 🔴 Робота, ЯКА ВЖЕ ЗРОБЛЕНА, дорожча за кілька хвилин оренди.
        # Наглядач не пам'ятав останній прогрес: при мертвому SSH `progress`
        # стає None, і `decide` більше не знав, що фаза була `done`. Сценарій —
        # справа дорахована, ssh-проксі Vast флапнув 90 с → бокс із ПОВНИМ
        # результатом знищено, аварійний забір без SSH не бере нічого, і все
        # переорендовується з нуля. Тому там, де робота завершена, терпіння
        # значно довше: втратити готове гірше, ніж доплатити за очікування.
        ssh_cap = (cfg.ssh_fail_streak_max_done if obs.last_phase in ("done", "failed")
                   else cfg.ssh_fail_streak_max)
        if obs.ssh_fail_streak >= ssh_cap:
            return "destroy_dead_box", (
                f"SSH не відповідає {obs.ssh_fail_streak} тіки поспіль — бокс втрачено"
            )

    # ── 2. строк ───────────────────────────────────────────────────────────
    if obs.elapsed_h > cfg.max_hours:
        return "destroy_deadline", (
            f"{obs.elapsed_h:.1f} год від старту при стелі {cfg.max_hours:.1f} — "
            f"гашу на найсвіжішому чекпоінті"
        )

    # ── 3. гроші ───────────────────────────────────────────────────────────
    if obs.spent_usd >= cfg.budget_usd:
        return "destroy_budget", (
            f"витрачено ${obs.spent_usd:.2f} з ${cfg.budget_usd:.2f} — бюджет вичерпано"
        )
    projected = obs.projected_total_usd()
    # 🔴🔴 Прогноз робиться ЛИШЕ з дозрілого заміру. Темп у перші хвилини — це
    # не темп: бокс тягне тригігабайтний архів кадрів, розпаковує його, ставить
    # пакети, шарди ще не вийшли на режим — і «сторінок за годину» майже нуль.
    # Прогноз від такого числа сміттєвий, а запобіжник рахує від того, що
    # виміряв, і сам себе спиняє. Тричі поспіль 2026-08-12, найгірше — на боксі
    # з найважчою справою (3.7 ГБ): «за виміряним темпом 120 стор/год вийде
    # $6.23» на машині, яка ще не прочитала жодного аркуша.
    # Жорсткий поріг «витрачено ≥ бюджет» (вище) від цього не залежить і працює
    # завжди — тобто гроші лишаються під захистом.
    if (obs.throughput_settled
            and projected > cfg.budget_usd - cfg.reserve_usd and obs.pages_left > 0):
        return "destroy_budget", (
            f"за виміряним темпом ({obs.pages_per_hour:.0f} стор/год) вийде "
            f"${projected:.2f} при бюджеті ${cfg.budget_usd:.2f} — спиняю зараз, "
            f"поки результат ще можна забрати"
        )

    # ── 3-тер. ГРОШІ НА ЦЬОМУ БОКСІ проти сторінок, які він видав ──────────
    # 🔴🔴 Правило нижче (3-біс) бере темп, який раннер САМ про себе пише, і
    # порівнює з абсолютною стелею. У P2 06.09.2026 бокс завис між справами,
    # прогрес завмер на останньому хорошому темпі — і «ціна» лишалась гарною,
    # поки лічильник грошей ішов годину. Тут рахується інше: скільки грошей
    # пішло на ЦЮ оренду й скільки сторінок вона реально дала. Еталон — ціна,
    # яку цей самий бокс уже показував на живому темпі. Бокс, що коштує вдвічі
    # більше за самого себе, — це зависання, обсипаний флот або машина, яку
    # хтось іще навантажив; за ці гроші робота піде на іншій.
    #
    # 🔴🔴 Лише ВІД ДОЗРІЛОГО темпу і лише проти ВЛАСНОЇ ціни боксу. Перша
    # версія рахувала гроші від створення інстансу, а поки темп не дозрів,
    # еталоном брала прогноз на повний флот. Регулятор (10.09.2026) виходить
    # на флот поступово, сетап із качанням кадрів черги триває 5–10 хв — і
    # 11.09.2026 (904-24-70) правило двічі погасило здорові бокси: живі $0.078
    # і $0.104 за 1000 проти «за орендою» $0.140 і $0.138. До дозрівання
    # зависання ловлять `stale_progress_sec` і сторож сетапу.
    if (obs.box_best_usd_per_1000 > 0 and obs.rent_usd > 0
            and obs.rent_settled_sec >= cfg.rent_price_min_age_sec):
        actual = obs.rent_usd / max(obs.rent_pages, 1) * 1000.0
        reference = obs.box_best_usd_per_1000
        if actual > cfg.rent_price_tolerance * reference:
            return "rerent", (
                f"ця оренда вже коштує ${actual:.3f} за 1000 сторінок "
                f"(${obs.rent_usd:.2f} за {obs.rent_pages} стор. за "
                f"{obs.rent_settled_sec / 60:.0f} хв після дозрівання темпу) проти "
                f"${reference:.3f}, які цей бокс показував сам — "
                f"{actual / reference:.1f}× дорожче; гашу на найсвіжішому "
                f"чекпоінті, решту дочитає інший"
            )

    # ── 3-біс. ЦІНА СТОРІНКИ на живому темпі ───────────────────────────────
    # 🔴🔴 Стеля $/1000 перевірялась ЛИШЕ при виборі оффера — тобто на
    # ПРОГНОЗІ. А прогноз не знає, що за матеріал: сповідки з їхніми щільними
    # графами йдуть удвічі повільніше за метрики на тій самій машині.
    # Заміряно 2026-08-12: Q RTX 6000 за $0.211/год мала в реєстрі замір
    # 1562 стор/год (зроблений на МЕТРИЦІ) і модельний прогноз 1600 — обидва
    # обіцяли ~$0.135 за тисячу. Реальність на сповідках: 882 стор/год і
    # **$0.239**, тобто на 20% вище стелі, і ніхто цього не помічав.
    # Не гасимо: робота вже йде, а знищити її дорожче за переплату. Але
    # називаємо вголос, щоб рішення ухвалювала людина, а не тиша.
    if obs.throughput_settled and obs.usd_per_1000 > cfg.max_usd_per_1000:
        # 🔴🔴 Гасимо, лише коли перевищення ВИСТОЯЛОСЬ. Одна просадка темпу —
        # це важкий аркуш або качання наступної справи, а не стан машини;
        # знищити по ній бокс означає викинути вже оплачену роботу. Але коли
        # ціна тримається — переплата вже не «трохи»: на машині 139040 за ті
        # самі гроші, що пішли на ОДНУ справу, проходить десяток.
        if (obs.price_breach_sec >= cfg.price_breach_grace_sec
                and obs.price_breach_streak >= cfg.price_breach_streak_max):
            return "destroy_overpriced", (
                f"ціна сторінки тримається ${obs.usd_per_1000:.3f} за 1000 вже "
                f"{obs.price_breach_sec / 60:.0f} хв ({obs.price_breach_streak} замірів "
                f"поспіль) при стелі ${cfg.max_usd_per_1000:.2f} — це не просадка, а "
                f"стан машини; гашу на найсвіжішому чекпоінті, за ці гроші пройде "
                f"більше справ деінде"
            )
        return "price_alert", (
            f"ціна сторінки на ЖИВОМУ темпі ${obs.usd_per_1000:.3f} за 1000 "
            f"(темп {obs.pages_per_hour:.0f} стор/год, ${obs.dph:.3f}/год) — "
            f"вище стелі ${cfg.max_usd_per_1000:.2f}. Прогноз при виборі був "
            f"оптимістичний: цей матеріал важчий, ніж машина показувала раніше"
        )

    # ── 3-біс. теплий бокс: черга порожня, довісок приймається ────────────
    # 🔥 Фаза `idle` — не «мертвий раннер» і не «done»: бокс чекає `htr append`
    # ще `keep_warm_sec`. Правила 1–3 вище (мертвий бокс, строк, бюджет, ціна)
    # діють як і раніше; без цієї гілки правило 5 оголосило б застарілий
    # прогрес мертвим раннером і переорендувало б живий теплий бокс.
    if obs.phase == "idle":
        left = int((obs.progress or {}).get("idle_left_sec") or 0)
        return "wait", (
            f"черга порожня, бокс теплий ще {left / 60:.0f} хв — довісок "
            f"приймається (`gpurunner htr append`)"
        )

    # ── 4. справа завершилась ──────────────────────────────────────────────
    if obs.phase in ("done", "failed"):
        if obs.missing_count and obs.catchup_rounds_done < obs.catchup_passes:
            return "catchup", (
                f"бракує {obs.missing_count} сторінок — ЧЕКАЮ, поки раннер їх "
                f"дожене сам на живому боксі "
                f"(спроба {obs.catchup_rounds_done + 1} з {obs.catchup_passes})"
            )
        if obs.queue_left > 0:
            return "next_case", (
                f"справа завершена, у черзі ще {obs.queue_left} — беру наступну "
                f"на тому самому боксі (холодний старт коштує ~8 хв)"
            )
        return "fetch_and_finish", (
            "справа завершена — забираю, звіряю повноту і гашу оренду"
        )

    # ── 4-біс. ФЛОТ УМИРАЄ ─────────────────────────────────────────────────
    # 🔴🔴 Раннер публікує все потрібне (`pages_failed`, `oom_events`,
    # `shards[].alive`) з першої хвилини, а `decide` цього не читав — і захід у
    # колапсі виглядав як звичайне «wait»: `why` показував сталу «лишилось N»,
    # темп повз 2159 → 68, і півгодини це бачила лише людина (машина 39565,
    # 2026-08-19; 15 із 16 шардів мертві, 69 збоїв зі 196 спроб).
    #
    # Дія — `rerent`, а не гасіння: чекпоінти інкрементальні, тож підняти флот
    # заново дешевше, ніж дивитись, як він доїдає оренду. Обидві ознаки
    # вимагають витримки — окремий мертвий шард підніме вотчдог самого раннера.
    if obs.phase == "running" and obs.shards_total:
        if obs.shards_dead * 2 >= obs.shards_total and obs.dead_streak >= cfg.fail_streak_max:
            return "rerent", (
                f"впало {obs.shards_dead} шардів із {obs.shards_total} з ненульовим rc "
                f"(збоїв {obs.pages_failed}"
                + (f", OOM-подій {obs.oom_events}" if obs.oom_events else "")
                + "); піднімаю з чекпоінтів"
            )
        if (obs.fail_ratio > cfg.fail_ratio_max
                and obs.fail_streak >= cfg.fail_streak_max
                and obs.fail_attempts >= cfg.fail_min_attempts):
            return "rerent", (
                f"{obs.fail_ratio:.0%} спроб у збоях ({obs.pages_failed_active} з "
                f"{obs.fail_attempts}"
                + (f", OOM-подій {obs.oom_events}" if obs.oom_events else "")
                + f") {obs.fail_streak} тіки поспіль — так флот не дорахує; "
                f"піднімаю з чекпоінтів"
            )

    # ── 5. раннер помер, бокс живий ────────────────────────────────────────
    if (obs.progress is None and obs.progress_age_sec > cfg.first_progress_sec
            and obs.progress_miss_streak >= cfg.progress_miss_streak_max):
        # 🔴 Не `rerent`. Робота не почалась ЖОДНОГО разу, тобто справа не в
        # машині: інший бокс не отримає ні моделей, ні кадрів так само.
        # Переоренда тут лише подвоїла б рахунок.
        return "startup_failed", (
            f"за {obs.progress_age_sec / 60:.0f} хв бокс не порахував жодної "
            f"сторінки — робота не почалась узагалі (найчастіше: не доїхали "
            f"моделі або кадри). Інша машина не допоможе"
        )
    # 🔴 Поки триває СЕТАП (pip, ассети, кілька ГБ кадрів, розпакування),
    # публікувати нема чого — і це законно. Мірка тут мусить бути інша: справа
    # на 3.4 ГБ при пороговому каналі 20 Мбіт/с законно качається 20+ хвилин,
    # плюс ~8 хв pip; зі стелею 20 хв наглядач гасив би бокс, який щойно
    # ДОКАЧАВ дані, і другий помирав би так само — дві оренди, нуль сторінок.
    # 🔴 Сетап, який СТОЇТЬ. Годинна стеля нижче міряє час, а не рух, і
    # 50-хвилинне зависання на качанні архіву крізь неї проходить.
    # 🔴🔴 І МІЖ справами теж, не лише до першого прогресу. 06.09.2026 (P2,
    # ф.230): друга справа черги зависла на качанні кадрів, прогрес від
    # першої справи вже існував, тож ця гілка не спрацювала — і наглядач
    # чекав повну годину `setup_max_sec`. Сетап — це будь-яка фаза, у якій
    # шарди не працюють: старт, качання, розпакування.
    if (obs.ssh_ok and obs.phase in SETUP_PHASES
            and obs.setup_stall_sec_seen > cfg.setup_stall_sec):
        return "rerent", (
            f"сетап не посувається {obs.setup_stall_sec_seen / 60:.0f} хв: лог "
            f"раннера не росте при живому SSH — бокс завис (найчастіше на "
            f"качанні архіву); беру інший"
        )
    stale_cap = (cfg.stale_progress_sec if obs.phase == "running"
                 else cfg.setup_max_sec)
    if obs.progress is not None and obs.progress_age_sec > stale_cap:
        return "rerent", (
            f"прогрес не оновлювався {obs.progress_age_sec / 60:.0f} хв при живому SSH — "
            f"раннер помер (шарди вотчдог підняв би сам); піднімаю з чекпоінтів"
        )

    # ── 6. усе гаразд ──────────────────────────────────────────────────────
    if obs.pages_left and obs.pages_per_hour:
        eta_min = 60 * obs.pages_left / obs.pages_per_hour
        return "wait", (
            f"лишилось {obs.pages_left} сторінок, {obs.pages_per_hour:.0f} стор/год "
            f"— ще ~{eta_min:.0f} хв"
        )
    return "wait", f"фаза «{obs.phase or 'старт'}», прогрес свіжий"
