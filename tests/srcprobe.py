"""Читання ДЖЕРЕЛА в сторожах: тіло методу без фіксованих вікон.

🔴 Навіщо окремий модуль. Сторожі, які дивляться в текст коду, двічі за один
вечір 23.09.2026 зламались від ДОДАНОГО КОМЕНТАРЯ: `src[i:i + 2500]` і
`src[i:i + 4000]` відрізали саме ту перевірку, заради якої існували, і тест
повідомив про відсутність того, що на місці. Хибне червоне послаблюють — межу
підіймають, аж поки сторож не перестане ловити свою ваду.

Тому межа тут не в символах, а в структурі: тіло методу — до наступного `def`
того самого рівня.
"""

from __future__ import annotations


def method_body(src: str, name: str) -> str:
    """Тіло методу `name` — від його `def` до наступного `def` того ж рівня."""
    i = src.index(f"def {name}")
    nxt = src.find("\n    def ", i + 1)
    return src[i:nxt if nxt != -1 else len(src)]
